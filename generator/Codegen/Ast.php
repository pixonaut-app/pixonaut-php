<?php

declare(strict_types=1);

namespace Pixonaut\Sdk\Generator\Codegen;

use PhpParser\Comment;
use PhpParser\Comment\Doc;
use PhpParser\Node;
use PhpParser\Node\Arg;
use PhpParser\Node\Expr;
use PhpParser\Node\Identifier;
use PhpParser\Node\Name;
use PhpParser\Node\Scalar;
use PhpParser\Node\Stmt;

/**
 * Short constructors for the PHP-Parser nodes the printers build.
 */
final class Ast
{
    /** What `bin/generate` writes above every generated class. */
    private const HEADER = '// Generated by bin/generate from spec/openapi.json. Do not edit; change the generator or the spec.';

    /**
     * @param list<Arg|Expr> $args
     */
    public static function call(string $class, string $method, array $args): Expr\StaticCall
    {
        return new Expr\StaticCall(new Name($class), $method, self::args($args));
    }

    /**
     * @param list<Arg|Expr> $args
     */
    public static function func(string $name, array $args): Expr\FuncCall
    {
        return new Expr\FuncCall(new Name($name), self::args($args));
    }

    public static function named(string $name, Expr $value): Arg
    {
        return new Arg($value, false, false, [], new Identifier($name));
    }

    public static function var(string $name): Expr\Variable
    {
        return new Expr\Variable($name);
    }

    public static function this(string $property): Expr\PropertyFetch
    {
        return new Expr\PropertyFetch(new Expr\Variable('this'), $property);
    }

    public static function string(string $value): Scalar\String_
    {
        return new Scalar\String_($value);
    }

    public static function null(): Expr\ConstFetch
    {
        return new Expr\ConstFetch(new Name('null'));
    }

    public static function constant(string $class, string $name): Expr\ClassConstFetch
    {
        return new Expr\ClassConstFetch(new Name($class), $name);
    }

    public static function value(mixed $value): Expr
    {
        return match (true) {
            $value === null => self::null(),
            is_bool($value) => new Expr\ConstFetch(new Name($value ? 'true' : 'false')),
            is_int($value) && $value < 0 => new Expr\UnaryMinus(new Scalar\Int_(-$value)),
            is_int($value) => new Scalar\Int_($value),
            is_float($value) => new Scalar\Float_($value),
            is_string($value) => self::string($value),
            is_array($value) => new Expr\Array_(array_map(
                static fn(mixed $item, int|string $key): Node\ArrayItem => new Node\ArrayItem(
                    self::value($item),
                    array_is_list($value) ? null : self::value($key),
                ),
                $value,
                array_keys($value),
            )),
            default => throw new GeneratorException('Cannot print ' . get_debug_type($value) . '.'),
        };
    }

    /**
     * @param list<Expr> $items
     */
    public static function list(array $items): Expr\Array_
    {
        return new Expr\Array_(array_map(static fn(Expr $item): Node\ArrayItem => new Node\ArrayItem($item), $items));
    }

    /**
     * `static fn(mixed $v, string $p): <type> => <expr>`, the shape every
     * decoder callback has.
     */
    public static function decoder(string $returnType, Expr $body): Expr\ArrowFunction
    {
        return new Expr\ArrowFunction([
            'static' => true,
            'params' => [
                new Node\Param(self::var('v'), null, new Identifier('mixed')),
                new Node\Param(self::var('p'), null, new Identifier('string')),
            ],
            'returnType' => self::type($returnType),
            'expr' => $body,
        ]);
    }

    /**
     * A declared type from its spelling, e.g. `?string`, `A|B|null`.
     */
    public static function type(string $type): Node\ComplexType|Identifier|Name
    {
        if (str_starts_with($type, '?')) {
            return new Node\NullableType(self::singleType(substr($type, 1)));
        }
        if (str_contains($type, '|')) {
            return new Node\UnionType(array_map(self::singleType(...), explode('|', $type)));
        }

        return self::singleType($type);
    }

    /**
     * @param list<string> $lines Without the leading ` * `; a line may hold line breaks.
     */
    public static function doc(array $lines): ?Doc
    {
        $body = [];
        foreach ($lines as $line) {
            foreach (explode("\n", str_replace('*/', '*\/', rtrim($line))) as $part) {
                $body[] = rtrim(' * ' . $part);
            }
        }
        while ($body !== [] && $body[array_key_last($body)] === ' *') {
            array_pop($body);
        }

        return $body === [] ? null : new Doc("/**\n" . implode("\n", $body) . "\n */");
    }

    /**
     * A file holding one class.
     *
     * @param list<string> $uses Fully qualified classes to import.
     */
    public static function file(string $namespace, array $uses, Stmt\Class_ $class): string
    {
        sort($uses);
        $statements = array_map(static fn(string $use): Stmt\Use_ => new Stmt\Use_([new Node\UseItem(new Name($use))]), array_values(array_unique($uses)));
        if ($statements !== []) {
            $statements[] = new Stmt\Nop();
        }
        $class->stmts = self::spaced(array_values($class->stmts));
        $statements[] = $class;
        $file = new Stmt\Namespace_(new Name($namespace), $statements);
        $declare = new Stmt\Declare_([new Node\DeclareItem('strict_types', new Scalar\Int_(1))]);
        $header = new Stmt\Nop();
        $header->setAttribute('comments', [new Comment(self::HEADER)]);
        $code = (new CodePrinter())->prettyPrintFile([$declare, new Stmt\Nop(), $header, new Stmt\Nop(), $file]);

        // A blank line printed by a `Nop` is indented like its neighbours.
        return (preg_replace('/[ ]+$/m', '', $code) ?? $code) . "\n";
    }

    /**
     * Class members with a blank line between each.
     *
     * @param list<Stmt> $statements
     *
     * @return list<Stmt>
     */
    private static function spaced(array $statements): array
    {
        $spaced = [];
        foreach ($statements as $statement) {
            if ($spaced !== []) {
                $spaced[] = new Stmt\Nop();
            }
            $spaced[] = $statement;
        }

        return $spaced;
    }

    /**
     * @param list<Arg|Expr> $args
     *
     * @return list<Arg>
     */
    private static function args(array $args): array
    {
        return array_map(static fn(Arg|Expr $arg): Arg => $arg instanceof Arg ? $arg : new Arg($arg), $args);
    }

    private static function singleType(string $type): Identifier|Name
    {
        if (str_starts_with($type, '\\')) {
            return new Name\FullyQualified(substr($type, 1));
        }

        return in_array($type, ['string', 'int', 'float', 'bool', 'array', 'mixed', 'null', 'self', 'void', 'never'], true)
            ? new Identifier($type)
            : new Name($type);
    }
}
